def main() -> int:
    src = DART.read_text(encoding="utf-8")
    en_block = src[src.index("_english = {"):src.index("static const Map<String, String> _portuguese")]
    entries = re.findall(r"^\s+'([^']+)':\s*'(.*)',\s*$", en_block, re.M)
    out = ["  static const Map<String, String> _spanish = {"]
    missing = 0
    for key, en_val in entries:
        val = T.get(key, en_val)
        if val == en_val and en_val != "Discipolat":
            missing += 1
        # escape single quotes for Dart
        val_esc = val.replace("\\", "\\\\").replace("'", "\\'")
        out.append(f"    '{key}': '{val_esc}',")
    out.append("  };")
    block = "\n".join(out)

    anchor = "class _AppLocalizationsDelegate"
    if "static const Map<String, String> _spanish = {" in src:
        # replace the existing (stale) block in place
        start = src.index("  static const Map<String, String> _spanish = {")
        # block ends at the next two-space top-level `};`
        end = src.index("\n  };", start) + len("\n  };")
        new_src = src[:start] + block + src[end:]
        print(f"Replaced _spanish with {len(entries)} keys ({missing} fell back to English)")
        DART.write_text(new_src, encoding="utf-8")
        return 0
    new_src = src.replace(anchor, block + "\n\n" + anchor, 1)
    DART.write_text(new_src, encoding="utf-8")
    print(f"Inserted _spanish with {len(entries)} keys ({missing} fell back to English)")
    return 0


