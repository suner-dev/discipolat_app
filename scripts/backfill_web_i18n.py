def load_dict(path):
    src = path.read_text()
    return dict(re.findall(r"'([^']+)': '([^']*)'", src))


def insert_missing(path, translations):
    src = path.read_text()
    existing = dict(re.findall(r"'([^']+)': '([^']*)'", src))
    missing = {k: v for k, v in translations.items() if k not in existing}
    if not missing:
        print(f'  {path.name}: already complete')
        return
    # Insert sorted before the closing `};`
    lines = src.split('\n')
    for i, line in enumerate(lines):
        if line.strip() == '};':
            insert_at = i
            break
    block = []
    for k in sorted(missing):
        block.append(f"  '{k}': '{missing[k]}',")
    lines[insert_at:insert_at] = block
    path.write_text('\n'.join(lines))
    print(f'  {path.name}: +{len(missing)} keys')


def main():
    for lang, translations in [('en', EN), ('pt', PT), ('es', ES), ('sw', SW), ('ar', AR)]:
        print(lang)
        insert_missing(I18N_DIR / f'{lang}.ts', translations)
    # Report remaining gaps
    fr = load_dict(I18N_DIR / 'fr.ts')
    for lang in ['en', 'pt', 'es', 'sw', 'ar']:
        d = load_dict(I18N_DIR / f'{lang}.ts')
        missing = [k for k in fr if k not in d]
        print(f'{lang}: {len(missing)} still missing vs fr')


