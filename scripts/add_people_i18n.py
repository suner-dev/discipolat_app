for loc, nav in NAV.items():
    path = os.path.join(BASE, f'{loc}.ts')
    src = io.open(path, encoding='utf-8').read()
    if "'people.title'" in src:
        print(f'{loc}: déjà présent, skip')
        continue
    anchor = f"'nav.organization': "
    idx = src.index(anchor)
    eol = src.index('\n', idx)
    nav_line = f"  'nav.repertoire': \"{nav}\",\n"
    src = src[:eol + 1] + nav_line + src[eol + 1:]
    block = '\n  // §G6.4 — Répertoire des personnes (/people)\n'
    for k, v in PEOPLE[loc].items():
        block += f"  '{k}': \"{v}\",\n"
    tail_idx = src.rindex('};')
    src = src[:tail_idx] + block + src[tail_idx:]
    io.open(path, 'w', encoding='utf-8').write(src)
    print(f'{loc}: OK')
