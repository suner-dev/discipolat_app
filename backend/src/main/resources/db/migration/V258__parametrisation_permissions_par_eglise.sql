-- ============================================================
-- PARAMÉTRISATION PAR ÉGLISE — catalogue canonique de permissions
-- + matrice par défaut à équivalence STRCTE avec les gardes codées
-- en dur (581 sites @PreAuthorize à littéral de rôle).
--
-- Généré par .e2e-tmp/gen_catalogue.py — vérité = source relué.
-- Additif : ne modifie AUCUNE ligne existante ; crée les rôles
-- legacy absents, les permissions du catalogue, et n'accorde une
-- permission à un rôle que si ce rôle la détenait déjà (union des
-- littéraux). Une église peut ensuite RETIRER ou AJOUTER n'importe
-- quelle capacité par rôle via la matrice (rôles per-tenant).
-- Cible PostgreSQL (Flyway désactivé sous H2/tests).
-- ============================================================

-- 1) Rôles legacy (clés d'autorité Spring) en rôles système globaux,
--    pour que la matrice role_permissions puisse les lier.
INSERT INTO roles (id, tenant_id, key, label, description, system, priority, created_at, updated_at)
SELECT uuid_generate_v4(), NULL, k.key, k.label, k.label, TRUE, k.priority, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM (VALUES
    ('ADMIN', 'Administrateur', 950),
    ('PASTEUR', 'Pasteur', 850),
    ('RESPONSABLE', 'Responsable de département', 400),
    ('CHEF_DE_FAMILLE', 'Chef de famille', 300),
    ('FAISEUR', 'Faiseur de disciples', 200),
    ('MEMBRE', 'Membre', 100)
) AS k(key, label, priority)
-- Guard STRICT sur le rôle GLOBAL (tenant_id IS NULL) : les clés legacy
-- ADMIN/PASTEUR/… doivent exister en rôles système pour que le pont
-- d'équivalence autorité→permission fonctionne, même si une église a
-- déjà une surcouche locale portant la même clé (UNIQUE (tenant_id, key)).
WHERE NOT EXISTS (SELECT 1 FROM roles ro WHERE ro.tenant_id IS NULL AND ro.key = k.key);

